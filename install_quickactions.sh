# Substitute the command string (XML-escape & < >) and fresh UUIDs.
ESCAPED=$(printf '%s' "${COMMAND_STRING}" | sed 's/&/\&amp;/g; s/</\&lt;/g; s/>/\&gt;/g')
python3 - "$SERVICE_DIR/document.wflow" <<PYEOF
import sys
path = sys.argv[1]
with open(path) as fh:
    data = fh.read()
data = data.replace("{{COMMAND_STRING}}", """${ESCAPED}""")
import uuid
data = data.replace("INPUT-UUID", str(uuid.uuid4()).upper())
data = data.replace("OUTPUT-UUID", str(uuid.uuid4()).upper())
data = data.replace("ACTION-UUID", str(uuid.uuid4()).upper())
with open(path, "w") as fh:
    fh.write(data)
PYEOF

# Refresh the Services menu so the new Quick Action shows up.
